-- 000_core_schema.sql
-- Esquema base de Osmio: perfiles, sesiones, nutrición, metas y catálogo.
--
-- IMPORTANTE: ejecutar ANTES de 001_exercises_extend.sql. Las migraciones 001-004
-- asumen que estas tablas ya existen (por eso el orden anterior no permitía
-- reconstruir la base desde cero).
--
-- Idempotente: usa `create table if not exists`, por lo que no altera la base
-- actual; solo crea lo que falte. Las políticas se recrean para garantizar que
-- coinciden con este archivo.
--
-- Nota sobre integridad: las FK a `auth.users` solo se aplican al crear la
-- tabla (base nueva). En la base existente no se añaden para no fallar si hay
-- filas huérfanas; endurecerlas allí requiere limpiar datos primero.

-- ---------------------------------------------------------------------------
-- Catálogo de ejercicios (base; 001 añade las columnas del dataset)
-- ---------------------------------------------------------------------------
create table if not exists public.exercises (
  id integer generated by default as identity primary key,
  name text not null,
  category text not null default '',
  type text not null default 'strength' check (type in ('strength', 'cardio'))
);

-- ---------------------------------------------------------------------------
-- Perfiles (1:1 con auth.users)
-- ---------------------------------------------------------------------------
create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  name text not null default '',
  email text not null default '',
  weight numeric(5, 2) check (weight is null or (weight > 0 and weight < 500)),
  height numeric(5, 2) check (height is null or (height > 0 and height < 300)),
  -- `age` la escribe profiles.api.ts; en la base original faltaba (ver 005).
  age integer check (age is null or (age between 10 and 120)),
  experience text check (experience in ('beginner', 'intermediate', 'advanced')),
  goal text check (goal in ('strength', 'combat', 'both')),
  created_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- Entrenamiento de fuerza
-- ---------------------------------------------------------------------------
create table if not exists public.strength_sessions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users (id) on delete cascade,
  date date not null,
  exercise_id integer references public.exercises (id),
  exercise_name text not null,
  notes text,
  created_at timestamptz not null default now()
);

create table if not exists public.set_entries (
  id uuid primary key default gen_random_uuid(),
  session_id uuid not null references public.strength_sessions (id) on delete cascade,
  set_order integer not null check (set_order >= 1),
  reps integer not null check (reps >= 0),
  weight numeric(6, 2) not null check (weight >= 0),
  rpe numeric(3, 1) check (rpe is null or (rpe between 1 and 10))
);

-- ---------------------------------------------------------------------------
-- Deportes de combate
-- ---------------------------------------------------------------------------
create table if not exists public.combat_sessions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users (id) on delete cascade,
  date date not null,
  type text not null check (type in ('striking', 'grappling')),
  combat_type text check (combat_type in ('competencia', 'sparring', 'clase')),
  result text check (result in ('victoria', 'derrota', 'empate')),
  rounds integer not null check (rounds between 1 and 12),
  duration_minutes numeric(4, 1) not null check (duration_minutes > 0),
  rpe numeric(3, 1) check (rpe is null or (rpe between 1 and 10)),
  positions text[],
  notes text,
  created_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- Nutrición y composición corporal
-- ---------------------------------------------------------------------------
create table if not exists public.meals (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users (id) on delete cascade,
  name text not null,
  calories numeric(6, 1) not null check (calories >= 0),
  protein numeric(5, 1) not null check (protein >= 0),
  carbs numeric(5, 1) not null check (carbs >= 0),
  fat numeric(5, 1) not null check (fat >= 0),
  logged_at timestamptz not null default now()
);

create table if not exists public.frequent_meals (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users (id) on delete cascade,
  name text not null,
  calories numeric(6, 1) not null check (calories >= 0),
  protein numeric(5, 1) not null check (protein >= 0),
  carbs numeric(5, 1) not null check (carbs >= 0),
  fat numeric(5, 1) not null check (fat >= 0),
  created_at timestamptz not null default now()
);

-- Una meta por usuario: la PK en user_id permite el upsert con onConflict.
create table if not exists public.nutrition_goals (
  user_id uuid primary key references auth.users (id) on delete cascade,
  calories numeric(6, 1) not null check (calories >= 0),
  protein numeric(5, 1) not null check (protein >= 0),
  carbs numeric(5, 1) not null check (carbs >= 0),
  fat numeric(5, 1) not null check (fat >= 0),
  updated_at timestamptz not null default now()
);

create table if not exists public.body_weight (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users (id) on delete cascade,
  date date not null,
  weight numeric(5, 2) not null check (weight > 0 and weight < 500),
  unique (user_id, date)
);

-- ---------------------------------------------------------------------------
-- Recuperación y preferencias
-- ---------------------------------------------------------------------------
create table if not exists public.daily_recovery (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users (id) on delete cascade,
  date date not null,
  sleep_quality integer check (sleep_quality is null or (sleep_quality between 0 and 100)),
  hydration_liters numeric(3, 1) check (hydration_liters is null or (hydration_liters >= 0 and hydration_liters <= 20)),
  resting_hr integer check (resting_hr is null or (resting_hr between 20 and 220)),
  source text not null default 'manual' check (source in ('manual', 'wearable')),
  created_at timestamptz not null default now(),
  unique (user_id, date)
);

create table if not exists public.training_days (
  user_id uuid primary key references auth.users (id) on delete cascade,
  monday boolean not null default false,
  tuesday boolean not null default false,
  wednesday boolean not null default false,
  thursday boolean not null default false,
  friday boolean not null default true,
  saturday boolean not null default true,
  sunday boolean not null default true
);

create table if not exists public.weekly_goals (
  user_id uuid primary key references auth.users (id) on delete cascade,
  strength integer not null default 2 check (strength >= 0),
  combat integer not null default 4 check (combat >= 0),
  nutrition integer not null default 7 check (nutrition >= 0),
  updated_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- Índices de consulta (los mismos que usa el módulo de análisis)
-- ---------------------------------------------------------------------------
create index if not exists idx_strength_sessions_user_date
  on public.strength_sessions (user_id, date);
create index if not exists idx_combat_sessions_user_date
  on public.combat_sessions (user_id, date);
create index if not exists idx_meals_user_date
  on public.meals (user_id, logged_at);

-- ---------------------------------------------------------------------------
-- Row Level Security: cada usuario solo ve y escribe sus propias filas.
-- ---------------------------------------------------------------------------
alter table public.profiles enable row level security;
alter table public.strength_sessions enable row level security;
alter table public.set_entries enable row level security;
alter table public.combat_sessions enable row level security;
alter table public.meals enable row level security;
alter table public.frequent_meals enable row level security;
alter table public.nutrition_goals enable row level security;
alter table public.body_weight enable row level security;
alter table public.daily_recovery enable row level security;
alter table public.training_days enable row level security;
alter table public.weekly_goals enable row level security;
alter table public.exercises enable row level security;

drop policy if exists "Users can view own profile" on public.profiles;
create policy "Users can view own profile" on public.profiles
  for select using (auth.uid() = id);

drop policy if exists "Users can insert own profile" on public.profiles;
create policy "Users can insert own profile" on public.profiles
  for insert with check (auth.uid() = id);

drop policy if exists "Users can update own profile" on public.profiles;
create policy "Users can update own profile" on public.profiles
  for update using (auth.uid() = id) with check (auth.uid() = id);

drop policy if exists "Users manage own strength sessions" on public.strength_sessions;
create policy "Users manage own strength sessions" on public.strength_sessions
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists "Users manage sets of own sessions" on public.set_entries;
create policy "Users manage sets of own sessions" on public.set_entries
  for all
  using (exists (
    select 1 from public.strength_sessions s
    where s.id = set_entries.session_id and s.user_id = auth.uid()
  ))
  with check (exists (
    select 1 from public.strength_sessions s
    where s.id = set_entries.session_id and s.user_id = auth.uid()
  ));

drop policy if exists "Users manage own combat sessions" on public.combat_sessions;
create policy "Users manage own combat sessions" on public.combat_sessions
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists "Users manage own meals" on public.meals;
create policy "Users manage own meals" on public.meals
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists "Users manage own frequent meals" on public.frequent_meals;
create policy "Users manage own frequent meals" on public.frequent_meals
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

