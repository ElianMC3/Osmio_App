create policy "Users manage own body weight" on public.body_weight
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists "Users manage own daily recovery" on public.daily_recovery;
create policy "Users manage own daily recovery" on public.daily_recovery
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists "Users manage own training days" on public.training_days;
create policy "Users manage own training days" on public.training_days
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

